
BEGIN;

-- =========================================================
-- 1. COUNTRIES
-- Clients reference a country through pais_id.
-- =========================================================

CREATE TABLE paises (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    codigo CHAR(2) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL UNIQUE,

    CONSTRAINT chk_paises_codigo
        CHECK (codigo ~ '^[A-Z]{2}$')
);

INSERT INTO paises (codigo, nombre)
VALUES
    ('ES', 'España'),
    ('PT', 'Portugal'),
    ('FR', 'Francia')
ON CONFLICT (codigo) DO NOTHING;


-- =========================================================
-- 2. SALESPEOPLE
-- =========================================================

CREATE TABLE comerciales (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 3. USERS
-- Passwords must be stored as secure password hashes.
-- JWT authentication will be implemented in the API.
-- =========================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uq_usuarios_email_lower
    ON usuarios (LOWER(email));


-- =========================================================
-- 4. CLIENTS
-- nombre_normalizado is maintained by the application.
-- It must contain the canonical company name used for
-- consolidation, not merely the original CSV spelling.
-- =========================================================

CREATE TABLE clientes (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    empresa VARCHAR(255) NOT NULL,
    nombre_normalizado VARCHAR(255) NOT NULL UNIQUE,
    cif VARCHAR(30),

    direccion VARCHAR(255),
    codigo_postal VARCHAR(20),
    ciudad VARCHAR(120),

    pais_id BIGINT NOT NULL
        REFERENCES paises(id) ON DELETE RESTRICT,

    comercial_id BIGINT
        REFERENCES comerciales(id) ON DELETE RESTRICT,

    estado VARCHAR(10) NOT NULL DEFAULT 'Activo'
        CHECK (estado IN ('Activo', 'Inactivo')),

    fecha_alta DATE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Soft deletion preserves the client and its audit history.
    deleted_at TIMESTAMPTZ,

    CONSTRAINT chk_clientes_empresa_not_empty
        CHECK (LENGTH(TRIM(empresa)) > 0)
);

-- CIF is optional because the source CSV contains missing CIFs.
-- When present, a normalized CIF must identify one client.
CREATE UNIQUE INDEX uq_clientes_cif
    ON clientes (UPPER(cif))
    WHERE cif IS NOT NULL;

CREATE INDEX idx_clientes_estado
    ON clientes (estado)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_clientes_pais
    ON clientes (pais_id)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_clientes_comercial
    ON clientes (comercial_id)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_clientes_empresa
    ON clientes (LOWER(empresa))
    WHERE deleted_at IS NULL;


-- =========================================================
-- 5. CONTACTS
-- One client can have multiple contacts.
-- Phone numbers should include their international prefix.
-- =========================================================

CREATE TABLE contactos (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT NOT NULL
        REFERENCES clientes(id) ON DELETE RESTRICT,

    nombre VARCHAR(150) NOT NULL,
    email VARCHAR(254),
    telefono VARCHAR(30),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_contactos_nombre_not_empty
        CHECK (LENGTH(TRIM(nombre)) > 0)
);

CREATE INDEX idx_contactos_cliente
    ON contactos (cliente_id);

CREATE INDEX idx_contactos_email_lower
    ON contactos (LOWER(email))
    WHERE email IS NOT NULL;


-- =========================================================
-- 6. INVOICES
-- Taxable base and VAT are stored as exact decimals.
-- VAT amount and total are generated by PostgreSQL.
-- =========================================================

CREATE TABLE facturas (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT NOT NULL
        REFERENCES clientes(id) ON DELETE RESTRICT,

    numero_factura VARCHAR(100) NOT NULL,
    fecha_factura DATE NOT NULL,

    base_imponible NUMERIC(12, 2) NOT NULL
        CHECK (base_imponible >= 0),

    iva_porcentaje NUMERIC(5, 2) NOT NULL
        CHECK (iva_porcentaje >= 0 AND iva_porcentaje <= 100),

    importe_iva NUMERIC(12, 2)
        GENERATED ALWAYS AS (
            ROUND(base_imponible * iva_porcentaje / 100, 2)
        ) STORED,

    total NUMERIC(12, 2)
        GENERATED ALWAYS AS (
            base_imponible
            + ROUND(base_imponible * iva_porcentaje / 100, 2)
        ) STORED,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_facturas_cliente_numero
        UNIQUE (cliente_id, numero_factura),

    CONSTRAINT chk_facturas_numero_not_empty
        CHECK (LENGTH(TRIM(numero_factura)) > 0)
);

CREATE INDEX idx_facturas_cliente_fecha
    ON facturas (cliente_id, fecha_factura DESC);


-- =========================================================
-- 7. CLIENT CHANGE HISTORY
-- Supports changes to client fields and contact fields.
-- entidad_tipo: 'cliente' or 'contacto'.
-- valor_anterior / valor_nuevo preserve JSON values.
-- usuario_id may be NULL for system/import actions.
-- =========================================================

CREATE TABLE historico_cambios (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    cliente_id BIGINT NOT NULL
        REFERENCES clientes(id) ON DELETE RESTRICT,

    entidad_tipo VARCHAR(20) NOT NULL
        CHECK (entidad_tipo IN ('cliente', 'contacto')),

    entidad_id BIGINT NOT NULL,
    campo VARCHAR(100) NOT NULL,

    valor_anterior JSONB,
    valor_nuevo JSONB,

    usuario_id BIGINT
        REFERENCES usuarios(id) ON DELETE RESTRICT,

    actor_tipo VARCHAR(20) NOT NULL DEFAULT 'usuario'
        CHECK (actor_tipo IN ('usuario', 'sistema', 'importacion')),

    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_historico_cliente_fecha
    ON historico_cambios (cliente_id, fecha_hora DESC);

CREATE INDEX idx_historico_entidad
    ON historico_cambios (entidad_tipo, entidad_id);


-- =========================================================
-- 8. CSV IMPORT BATCHES
-- =========================================================

CREATE TABLE importaciones (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    nombre_archivo VARCHAR(255) NOT NULL,
    checksum_sha256 CHAR(64),

    estado VARCHAR(20) NOT NULL DEFAULT 'iniciada'
        CHECK (
            estado IN (
                'iniciada',
                'completada',
                'completada_con_incidencias',
                'fallida'
            )
        ),

    filas_totales INTEGER NOT NULL DEFAULT 0,
    filas_importadas INTEGER NOT NULL DEFAULT 0,
    filas_rechazadas INTEGER NOT NULL DEFAULT 0,
    filas_duplicadas INTEGER NOT NULL DEFAULT 0,

    iniciado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finalizado_en TIMESTAMPTZ,

    CONSTRAINT chk_importaciones_counts
        CHECK (
            filas_totales >= 0
            AND filas_importadas >= 0
            AND filas_rechazadas >= 0
            AND filas_duplicadas >= 0
        )
);


-- =========================================================
-- 9. IMPORT ISSUES
-- The importer will also write human-readable logs under /logs.
-- This table makes import issues queryable in PostgreSQL.
-- =========================================================

CREATE TABLE incidencias_importacion (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    importacion_id BIGINT NOT NULL
        REFERENCES importaciones(id) ON DELETE RESTRICT,

    fila_csv INTEGER,
    tipo VARCHAR(50) NOT NULL,

    severidad VARCHAR(10) NOT NULL DEFAULT 'error'
        CHECK (severidad IN ('info', 'warning', 'error')),

    descripcion TEXT NOT NULL,

    datos_originales JSONB,
    identificador_registro VARCHAR(255),

    estado VARCHAR(15) NOT NULL DEFAULT 'pendiente'
        CHECK (
            estado IN ('pendiente', 'revisada', 'resuelta')
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_incidencias_importacion
    ON incidencias_importacion (importacion_id, fila_csv);


-- =========================================================
-- 10. CLIENT UPDATE TIMESTAMP
-- The API will be responsible for writing audit entries.
-- =========================================================

CREATE OR REPLACE FUNCTION actualizar_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_clientes_updated_at
BEFORE UPDATE ON clientes
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

CREATE TRIGGER trg_contactos_updated_at
BEFORE UPDATE ON contactos
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

CREATE TRIGGER trg_facturas_updated_at
BEFORE UPDATE ON facturas
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();

CREATE TRIGGER trg_usuarios_updated_at
BEFORE UPDATE ON usuarios
FOR EACH ROW
EXECUTE FUNCTION actualizar_updated_at();


-- =========================================================
-- 11. CUMULATIVE BILLING VIEW
-- Includes only active (not soft-deleted) clients.
-- =========================================================

CREATE VIEW vista_facturacion_clientes AS
SELECT
    c.id AS cliente_id,
    COALESCE(SUM(f.base_imponible), 0)::NUMERIC(12, 2)
        AS facturacion_acumulada
FROM clientes c
LEFT JOIN facturas f
    ON f.cliente_id = c.id
WHERE c.deleted_at IS NULL
GROUP BY c.id;

COMMIT;
